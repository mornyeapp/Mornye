/// Material Symbols Rounded counterpart of a legacy Material icon.
///
/// [filled] keeps the legacy glyph's meaning: `_outlined`, `_outline`,
/// `_border` and `_none` icons stay empty, while the base and `_rounded`
/// variants keep their solid shape.
typedef MaterialSymbol = ({IconData icon, bool filled});

/// Rounded Material Symbols for the legacy icons used by the Material theme,
/// or null for icons without a counterpart (and for non-Material fonts).
///
/// Call sites keep `Icons.*` so the Mornye Cupertino mapping stays keyed by the
/// same constants.
MaterialSymbol? materialSymbolFor(IconData? icon) {
  if (icon == null || icon.fontFamily != Icons.add.fontFamily) return null;
  final filled = _filledSymbols[icon];
  if (filled != null) return (icon: filled, filled: true);
  final outlined = _outlinedSymbols[icon];
  if (outlined != null) return (icon: outlined, filled: false);
  return null;
}

